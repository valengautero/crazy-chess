export type TKey = keyof typeof es;
const dicts: Record<string, Record<TKey, string>> = { es };

/** Clave dinámica con respaldo (p. ej. mensajes de error del servidor). */
export function tDyn(key: string, fallback: TKey): string {
  return (es as Record<string, string>)[key] ?? es[fallback];
}
let lang = 'es';

export function t(key: TKey): string {
  return dicts[lang]?.[key] ?? es[key];
}

/** Traduce y reemplaza {marcadores}: tf('coach.best', { san: 'Cf3' }). */
export function tf(key: TKey, vars: Record<string, string | number> = {}): string {
  return t(key).replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}
